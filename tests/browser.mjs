import {mkdir,readFile} from 'node:fs/promises';
const modulePath=process.env.P2I_PLAYWRIGHT_MODULE??new URL('../../p2i-gui/frontend/node_modules/@playwright/test/index.mjs',import.meta.url).href;
const {chromium,expect}=await import(modulePath);
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1500,height:1100}});
const errors=[];page.on('pageerror',error=>errors.push(String(error)));
try{
 await page.goto(process.env.P2I_KG_URL??'http://127.0.0.1:8010');
 await expect(page.locator('#map .model-node')).toHaveCount(8);
 await expect(page.locator('#stats')).toContainText('8개 모델 · 12개 개념 · 8개 문헌');
 await expect(page.locator('#detail h2')).toHaveText('Transformer');
 await page.getByLabel('모델·개념·논문 검색',{exact:true}).fill('메모리 셀');
 await page.locator('#search-results [data-node="concept:memory_cell"]').click();
 await expect(page.locator('#detail')).toContainText('이 개념을 사용하는 모델');
 await expect(page.locator('#detail')).toContainText('LSTM');
 await page.getByLabel('모델·개념·논문 검색',{exact:true}).fill('');
 await page.getByLabel('비교할 첫 번째 모델',{exact:true}).selectOption('model:rnn');
 await page.getByLabel('비교할 두 번째 모델',{exact:true}).selectOption('model:lstm');
 await page.getByRole('button',{name:'모델 비교',exact:true}).click();
 await expect(page.locator('#comparison')).toContainText('메모리 셀');
 await page.locator('#map [data-node="model:lstm"]').click();
 await expect(page.locator('#detail h2')).toHaveText('LSTM');
 await page.getByRole('button',{name:'P2I로 열기 ↗',exact:true}).click();
 await expect(page.locator('#runtime-status')).toContainText('세션이 준비되었습니다.',{timeout:60000});
 const popupEvent=page.waitForEvent('popup');
 await page.getByRole('link',{name:'P2I 모델 탐색기 열기 ↗',exact:true}).click();
 const p2iPage=await popupEvent;
 await expect(p2iPage.locator('.explore-overview')).toBeVisible();
 await p2iPage.getByRole('button',{name:'Explore recurrent',exact:true}).click();
 await p2iPage.getByRole('button',{name:'Edit',exact:true}).click();
 await p2iPage.getByLabel('Constructor parameter',{exact:true}).selectOption('hidden_size');
 await p2iPage.getByLabel('Proposed value',{exact:true}).fill('12');
 await p2iPage.getByRole('button',{name:'Preview & validate',exact:true}).click();
 await expect(p2iPage.locator('.validation-result')).toContainText('Validation passed');
 await expect(p2iPage.locator('.diff-table')).toContainText('head');
 await p2iPage.getByRole('button',{name:'Commit edit',exact:true}).click();
 await p2iPage.getByRole('button',{name:'Build & Re-trace',exact:true}).click();
 await expect(p2iPage.locator('.local')).toContainText('architecture r1 / observed r1');
 const validation=await p2iPage.request.post(new URL('/api/harness/validate',p2iPage.url()).href,{data:{backward:true}});
 if(!(await validation.json()).result.backward_valid)throw Error('Edited KG model cannot backpropagate');
 await p2iPage.close();
 await page.getByRole('button',{name:'이 세션 닫기',exact:true}).click();
 await expect(page.locator('.session-link')).toHaveCount(0);
 const downloadEvent=page.waitForEvent('download');
 await page.getByRole('link',{name:'JSON-LD 내보내기 ↗',exact:true}).click();
 const download=await downloadEvent;
 await mkdir(new URL('../artifacts/',import.meta.url),{recursive:true});
 const path=new URL('../artifacts/catalog.jsonld',import.meta.url).pathname;
 await download.saveAs(path);
 if(JSON.parse(await readFile(path,'utf8'))['@graph'].length!==69)throw Error('Incomplete JSON-LD export');
 await page.locator('#map [data-node="model:transformer"]').click();
 await page.screenshot({path:new URL('../artifacts/atlas-desktop.png',import.meta.url).pathname,fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:new URL('../artifacts/atlas-mobile.png',import.meta.url).pathname,fullPage:true});
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS atlas: graph/search/evidence/compare, real P2I launch, connected recurrent edit, retrace/backward, session shutdown, JSON-LD and responsive views');
}finally{await browser.close()}
